#!/usr/bin/env python3
"""Convert carpipe sidecar JSON files into one Luau ModuleScript table (spec input for roblox/CarpipeRig.luau).

    python3 -I tools/blender/carpipe/sidecar_to_luau.py tools/blender/carpipe/out/*/*.json > CarpipeSpecs.luau
"""
import json
import sys

KEEP = ("name", "dimensions", "wheels", "seats", "lights", "paint", "exhausts", "center_of_mass_hint", "source")


def lua(v, ind=0):
    pad = "\t" * ind
    if isinstance(v, dict):
        if not v:
            return "{}"
        items = []
        for k, x in v.items():
            key = k if k.isidentifier() else f'["{k}"]'
            items.append(f"{pad}\t{key} = {lua(x, ind + 1)},")
        return "{\n" + "\n".join(items) + f"\n{pad}}}"
    if isinstance(v, list):
        if all(isinstance(x, (int, float)) for x in v):
            return "{ " + ", ".join(repr(round(x, 4)) if isinstance(x, float) else str(x) for x in v) + " }"
        return "{\n" + "\n".join(f"{pad}\t{lua(x, ind + 1)}," for x in v) + f"\n{pad}}}"
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "nil"
    if isinstance(v, (int, float)):
        return repr(v)
    return json.dumps(str(v))


def main(paths):
    out = {}
    for p in paths:
        d = json.load(open(p))
        out[d["name"]] = {k: d[k] for k in KEEP if k in d}
    print("--!strict\n-- Generated by tools/blender/carpipe/sidecar_to_luau.py. Do not edit by hand.\nreturn " +
          lua(out))


if __name__ == "__main__":
    main(sys.argv[1:])
