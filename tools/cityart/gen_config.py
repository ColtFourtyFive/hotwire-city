#!/usr/bin/env python3
"""Write src/shared/Config/CityArt.luau from tools/cityart/spec.py + assets/cityart/manifest.json, then run stylua on
it. Items without an uploaded assetId are left out (and reported), so the config only ever points at real assets."""
import os
import shutil
import subprocess
import sys
import json

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import spec  # noqa: E402

OUT = os.path.join(ROOT, "src", "shared", "Config", "CityArt.luau")
MANIFEST = os.path.join(ROOT, "assets", "cityart", "manifest.json")


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua_list(xs):
    return "{ " + ", ".join(lua_str(x) for x in xs) + " }" if xs else "{}"


def color(hexs):
    h = hexs.lstrip("#")
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    return "Color3.fromRGB(%d, %d, %d)" % (r, g, b)


def field(k, v):
    if v is None:
        return None
    if isinstance(v, bool):
        return "%s = %s" % (k, "true" if v else "false")
    if isinstance(v, (int, float)):
        return "%s = %s" % (k, v)
    if isinstance(v, list):
        return "%s = %s" % (k, lua_list(v))
    return "%s = %s" % (k, lua_str(v))


def record(fields):
    return "{ " + ", ".join(f for f in fields if f) + " }"


def main():
    man = json.load(open(MANIFEST))
    missing = []

    def image(item_id):
        e = man.get(item_id) or {}
        if not e.get("assetId"):
            missing.append(item_id)
            return None
        return "rbxassetid://%d" % e["assetId"]

    sizes = spec.SIZES
    L = []
    L.append("--!strict")
    L.append("-- GENERATED by tools/cityart/gen_config.py from tools/cityart/spec.py + assets/cityart/manifest.json.")
    L.append("-- Do not edit by hand: change the spec (or re-upload) and regenerate.")
    L.append("--")
    L.append("-- The city art pack: parody brand logos, billboard ads, storefront signs, street posters, graffiti and")
    L.append("-- loading key art, all uploaded as Image assets (usable in Decal/Texture/SurfaceGui ImageLabel). For the")
    L.append("-- world/buildings packages to dress billboards, shopfronts and props. Every brand is our own parody.")
    L.append("--   aspect: width:height of the image; size the face to match (CityArt.ASPECTS gives the ratio).")
    L.append("--   districts: WorldLayout district ids where the item fits (empty = anywhere).")
    L.append("--   poiBrand / poi: match WorldLayout POI.brand / POI.name so a POI can find its own sign.")
    L.append("")
    L.append('export type Aspect = "1:1" | "2:1" | "1:2" | "8:3" | "2:3" | "16:9"')
    L.append("export type Brand = {")
    L.append("\tname: string,")
    L.append("\tcategory: string,")
    L.append("\tlogo: string, -- 512x512 PNG with alpha")
    L.append("\tcolors: { Color3 }, -- primary first")
    L.append("\ttagline: string,")
    L.append("\tdistricts: { string },")
    L.append("\tpoiBrand: string?,")
    L.append("\tstation: string?, -- radio station name as used by Config/Sounds")
    L.append("\tsegment: string?, -- car makers: super / muscle / tuner")
    L.append("}")
    L.append("export type Billboard = { id: string, brand: string?, aspect: Aspect, image: string, copy: string }")
    L.append(
        'export type Sign = { id: string, key: string, brand: string?, name: string, '
        'kind: "fascia" | "awning" | "painted" | "pylon", '
        "aspect: Aspect, image: string, districts: { string }, poiBrand: string?, poi: string?, use: string? }"
    )
    L.append(
        'export type Poster = { id: string, kind: "flyer" | "poster" | "busstop", brand: string?, aspect: Aspect, '
        "image: string, title: string, districts: { string } }"
    )
    L.append(
        'export type Graffiti = { id: string, kind: "tag" | "stencil" | "mural", aspect: Aspect, image: string, '
        "alpha: boolean, districts: { string } }"
    )
    L.append("export type Loading = { id: string, title: string, aspect: Aspect, image: string }")
    L.append("")
    L.append("local CityArt = {}")
    L.append("")
    L.append("-- width / height for every aspect used here, and the uploaded pixel size")
    L.append("CityArt.ASPECTS = {")
    for a, (w, h) in sizes.items():
        n, d = a.split(":")
        L.append('\t["%s"] = %s / %s,' % (a, n, d))
    L.append("} :: { [string]: number }")
    L.append("CityArt.PIXELS = {")
    for a, (w, h) in sizes.items():
        L.append('\t["%s"] = { %d, %d },' % (a, w, h))
    L.append("} :: { [string]: { number } }")
    L.append("")

    L.append("CityArt.brands = {")
    for k, b in spec.BRANDS.items():
        img = image("logo_" + k)
        if not img:
            continue
        fs = [
            field("name", b["name"]),
            field("category", b["category"]),
            field("logo", img),
            "colors = { " + ", ".join(color(c) for c in b["colors"]) + " }",
            field("tagline", b["tagline"]),
            field("districts", b.get("districts", [])),
            field("poiBrand", b.get("poiBrand")),
            field("station", b.get("station")),
            field("segment", b.get("segment")),
        ]
        L.append("\t%s = %s," % (k, record(fs)))
    L.append("} :: { [string]: Brand }")
    L.append("")

    L.append("CityArt.billboards = {")
    for b in spec.BILLBOARDS:
        img = image(b["id"])
        if img:
            L.append("\t%s," % record([field("id", b["id"]), field("brand", b.get("brand")), field("aspect", b["aspect"]),
                                       field("image", img), field("copy", b["copy"])]))
    L.append("} :: { Billboard }")
    L.append("")

    L.append("CityArt.signs = {")
    for s in spec.SIGNS:
        img = image(s["id"])
        if not img:
            continue
        name = s.get("name") or spec.BRANDS[s["brand"]]["name"]
        L.append("\t%s," % record([
            field("id", s["id"]), field("key", s["id"].split("_", 1)[1]), field("brand", s.get("brand")),
            field("name", name), field("kind", s["kind"]),
            field("aspect", spec.SIGN_ASPECT[s["kind"]]), field("image", img), field("districts", s.get("districts", [])),
            field("poiBrand", s.get("poiBrand")), field("poi", s.get("poi")), field("use", s.get("use")),
        ]))
    L.append("} :: { Sign }")
    L.append("")

    L.append("CityArt.posters = {")
    for p in spec.POSTERS:
        img = image(p["id"])
        if img:
            L.append("\t%s," % record([
                field("id", p["id"]), field("kind", p["kind"]), field("brand", p.get("brand")), field("aspect", "2:3"),
                field("image", img), field("title", p["title"]), field("districts", p.get("districts", [])),
            ]))
    L.append("} :: { Poster }")
    L.append("")

    L.append("CityArt.graffiti = {")
    for g in spec.GRAFFITI:
        img = image(g["id"])
        if img:
            L.append("\t%s," % record([
                field("id", g["id"]), field("kind", g["kind"]), field("aspect", g["aspect"]), field("image", img),
                field("alpha", g["alpha"]), field("districts", g.get("districts", [])),
            ]))
    L.append("} :: { Graffiti }")
    L.append("")

    L.append("CityArt.loading = {")
    for item in spec.LOADING:
        img = image(item["id"])
        if img:
            L.append("\t%s," % record([field("id", item["id"]), field("title", item["title"]), field("aspect", "16:9"),
                                       field("image", img)]))
    L.append("} :: { Loading }")
    L.append("")

    L.append('''-- Lookups ------------------------------------------------------------------------------------------------------

local function inDistrict(list: { string }, district: string?): boolean
	if district == nil or #list == 0 then
		return true
	end
	return table.find(list, district) ~= nil
end

-- The storefront sign for a WorldLayout POI ({ name, brand? }): exact poi name, then POI.brand, then name prefix.
function CityArt.signForPoi(poi: { name: string, brand: string? }): Sign?
	for _, s in CityArt.signs do
		if s.poi == poi.name then
			return s
		end
	end
	if poi.brand then
		for _, s in CityArt.signs do
			if s.poiBrand == poi.brand then
				return s
			end
		end
	end
	for _, s in CityArt.signs do
		if s.poi and string.sub(poi.name, 1, #s.poi) == s.poi then
			return s
		end
	end
	return nil
end

-- Signs that suit a district (optionally one kind), for generic shop lots.
function CityArt.signsFor(district: string?, kind: string?): { Sign }
	local out = {}
	for _, s in CityArt.signs do
		if (kind == nil or s.kind == kind) and inDistrict(s.districts, district) then
			table.insert(out, s)
		end
	end
	return out
end

-- Billboards of one aspect ("2:1" roadside / rooftop, "1:2" building wraps / poles).
function CityArt.billboardsOf(aspect: Aspect): { Billboard }
	local out = {}
	for _, b in CityArt.billboards do
		if b.aspect == aspect then
			table.insert(out, b)
		end
	end
	return out
end

-- Deterministic pick from a list by seed (lot seed, edge id...), so every client dresses the city the same way.
function CityArt.pick<T>(list: { T }, seed: number): T?
	if #list == 0 then
		return nil
	end
	return list[(math.floor(math.abs(seed)) % #list) + 1]
end

return CityArt''')
    src = "\n".join(L) + "\n"
    with open(OUT, "w") as f:
        f.write(src)
    if shutil.which("stylua"):
        subprocess.run(["stylua", OUT], check=True, cwd=ROOT)
    print("wrote", OUT, "missing assetIds:", missing)


if __name__ == "__main__":
    main()
